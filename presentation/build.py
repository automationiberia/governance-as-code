#!/usr/bin/env python3
"""Build presentation/flow.html — a single self-contained file.

Inlines the vendored FlowStory engine and stylesheet (pinned, see
vendor/flowstory/VENDOR.md) and diagram.json, so the presentation opens with a
double click, offline, in any browser (no server: inline module scripts work
from file://, external module imports do not).

In the generated output only, the inspector's HTTP labels are replaced with
presentation labels; the vendored files are not modified.

Usage: python3 build.py            (run `node validate.mjs` first)
URL options of the result: flow.html?flow=<chapter-key>&step=<n>&theme=light
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
VENDOR = HERE / "vendor" / "flowstory"

LABELS = {  # engine literal -> presentation label
    '"Error Response"': '"Blocked"',
    '"Response"': '"Outcome"',
    '"Request"': '"Situation"',
    ">Headers:<": ">Status:<",
    ">Body:<": ">Evidence:<",
    ">CycleState:<": ">Decisions:<",
}


def engine_source() -> str:
    js = (VENDOR / "flowstory.min.js").read_text(encoding="utf-8")
    for old, new in LABELS.items():
        if old not in js:
            raise SystemExit(f"label {old!r} not found in the engine — check the vendored version")
        js = js.replace(old, new)
    # The bundle is an ES module ending in `export{a as Name,...};`. Inline it
    # and bind the exported names locally instead.
    match = re.search(r"export\{([^}]*)\};?\s*$", js)
    if not match:
        raise SystemExit("export statement not found in the engine")
    bindings = []
    for part in match.group(1).split(","):
        local, _, exported = part.strip().partition(" as ")
        bindings.append(f"{exported or local}={local}")
    return js[: match.start()] + "const " + ",".join(bindings) + ";"


def page(diagram: dict) -> str:
    css = (VENDOR / "style.css").read_text(encoding="utf-8")
    data = json.dumps(diagram, ensure_ascii=False).replace("</", "<\\/")
    title = diagram["meta"]["title"]
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
<!-- Generated by build.py from diagram.json — do not edit by hand. -->
<style>
{css}
</style>
</head>
<body>

<button class="fs-theme-toggle" id="fs-theme">&#9790;</button>
<div class="fs-brand" id="fs-brand"></div>
<div class="fs-title" id="fs-title"></div>

<div class="fs-panel">
  <div class="fs-flow-bar">
    <select id="fs-flow-select"></select>
    <button class="fs-start" id="fs-play">&#9654; Start</button>
    <button id="fs-speed">1x</button>
    <button id="fs-loop" style="border-color:#79c0ff;color:#79c0ff">&#8635; Loop</button>
    <button class="fs-reset" id="fs-reset">Reset</button>
  </div>
  <div class="fs-steps" id="fs-steps">
    <div class="fs-steps-title">Story <span style="font-weight:400;font-size:11px;color:var(--fs-text-dim)">· click a step to jump · click a box for details</span></div>
    <div id="fs-steps-container"></div>
  </div>
  <div class="fs-inspector" id="fs-inspector">
    <div class="fs-inspector-title" id="fs-inspector-title" style="color:var(--fs-accent)">Situation</div>
    <div id="fs-inspector-content"></div>
  </div>
</div>

<div id="fs-highlight-box" style="display:none;position:fixed;z-index:350;border-radius:10px;pointer-events:none"></div>
<div id="fs-overlay" style="display:none;position:fixed;top:0;left:0;right:380px;bottom:0;z-index:300;background:rgba(0,0,0,0.6)">
  <div id="fs-overlay-card" style="position:absolute;background:#161b22ee;border:1px solid #30363d;border-radius:14px;max-width:420px;padding:22px 26px;box-shadow:0 12px 40px rgba(0,0,0,0.5)">
    <button id="fs-overlay-close" style="position:absolute;top:10px;right:14px;background:none;border:none;color:#8b949e;font-size:18px;cursor:pointer;padding:4px 8px;border-radius:6px">✕</button>
    <div id="fs-overlay-accent" style="width:4px;height:24px;border-radius:2px;position:absolute;left:0;top:22px"></div>
    <h2 id="fs-overlay-title" style="margin:0 0 6px;font-size:18px;color:#c9d1d9;font-family:system-ui"></h2>
    <p id="fs-overlay-desc" style="margin:0 0 14px;font-size:13px;color:#8b949e;line-height:1.5;font-family:system-ui"></p>
    <div id="fs-overlay-details" style="font-size:12px;font-family:'SF Mono',Menlo,monospace"></div>
    <button id="fs-overlay-resume" style="margin-top:14px;padding:7px 20px;border:1px solid #3fb950;border-radius:8px;background:transparent;color:#3fb950;font-size:13px;cursor:pointer;font-family:system-ui">&#9654; Resume</button>
  </div>
</div>

<div class="fs-legend" id="fs-legend"></div>
<canvas id="fs-canvas"></canvas>

<script type="module">
{engine_source()}

const diagram = {data};

const $ = id => document.getElementById(id);
const viz = new FlowStory($('fs-canvas'), {{
  stepsContainer: $('fs-steps-container'), inspectorTitle: $('fs-inspector-title'),
  inspectorContent: $('fs-inspector-content'), overlay: $('fs-overlay'),
  overlayCard: $('fs-overlay-card'), overlayTitle: $('fs-overlay-title'),
  overlayDesc: $('fs-overlay-desc'), overlayDetails: $('fs-overlay-details'),
  overlayAccent: $('fs-overlay-accent'), overlayClose: $('fs-overlay-close'),
  overlayResume: $('fs-overlay-resume'), highlightBox: $('fs-highlight-box'),
  brand: $('fs-brand'), title: $('fs-title'), legend: $('fs-legend'),
  flowSelect: $('fs-flow-select'), playBtn: $('fs-play'), speedBtn: $('fs-speed'),
  loopBtn: $('fs-loop'), resetBtn: $('fs-reset'), themeBtn: $('fs-theme'),
}});
window.__flowstory = viz;

try {{
  await viz.load(diagram);
  const params = new URLSearchParams(location.search);
  if (params.get('theme') === 'light') viz.toggleTheme();
  const flow = params.get('flow');
  if (flow && diagram.flows[flow]) {{
    const select = $('fs-flow-select');
    select.value = flow;
    select.dispatchEvent(new Event('change'));
  }}
  const step = parseInt(params.get('step') || '0', 10);
  if (step > 0) viz.jumpTo(step - 1);
}} catch (e) {{
  console.error('FlowStory load error:', e);
  document.body.innerHTML = `<div style="padding:40px;color:#f85149;font-family:monospace"><h2>Load error</h2><pre>${{e.message}}\\n\\n${{e.stack || ''}}</pre></div>`;
}}
</script>
</body>
</html>
"""


def main() -> None:
    diagram = json.loads((HERE / "diagram.json").read_text(encoding="utf-8"))
    out = HERE / "flow.html"
    out.write_text(page(diagram), encoding="utf-8")
    print(f"wrote {out.relative_to(HERE.parent)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
