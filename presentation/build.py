#!/usr/bin/env python3
"""Build presentation/flow.html — a single self-contained file.

Inlines the vendored FlowStory engine and stylesheet (pinned, see
vendor/flowstory/VENDOR.md) and diagram.json, so the presentation opens with a
double click, offline, in any browser (no server: inline module scripts work
from file://, external module imports do not).

In the generated output only, the inspector's HTTP labels are replaced with
presentation labels; the vendored files are not modified.

Usage: python3 build.py            (run `node validate.mjs` first)
URL options of the result: flow.html?flow=<chapter-key>&step=<n>&theme=light
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
VENDOR = HERE / "vendor" / "flowstory"

LABELS = {  # engine literal -> presentation label
    '"Error Response"': '"Blocked"',
    '"Response"': '"Outcome"',
    '"Request"': '"Situation"',
    ">Headers:<": ">Status:<",
    ">Body:<": ">Evidence:<",
    # Live-demo steps put terminal + Cursor prompts here (diagram cycleState)
    ">CycleState:<": ">Commands:<",
}

# After LABELS, reorder the inspector so Commands (cycleState) is first and clickable.
# Vendor order is Status → Evidence → Commands; demo needs Commands at the top.
_INSPECTOR_RENDER_OLD = (
    "this.stepLabel&&(t+=`<div class=\"fs-inspector-plugin\">${z(this.stepLabel)}</div>`),"
    "t+='<div class=\"fs-inspector-section\">Status:</div>',"
    "this.headers.forEach(e=>{t+=`<div class=\"fs-inspector-line ${e.s}\">${z(e.v)}</div>`}),"
    "t+='<div class=\"fs-inspector-section\">Evidence:</div>',"
    "this.body.forEach(e=>{t+=`<div class=\"fs-inspector-line ${e.s}\">${z(e.v)}</div>`}),"
    "this.cycleState.length>0&&(t+='<div class=\"fs-inspector-section\">Commands:</div>',"
    "this.cycleState.forEach(e=>{t+=`<div class=\"fs-inspector-line ${e.s}\">${z(e.v)}</div>`})),"
    "this._contentEl.innerHTML=t"
)
_INSPECTOR_RENDER_NEW = (
    "this.stepLabel&&(t+=`<div class=\"fs-inspector-plugin\">${z(this.stepLabel)}</div>`),"
    "this.cycleState.length>0&&(t+='<div class=\"fs-inspector-section\">Commands:</div>',"
    "this.cycleState.forEach(e=>{t+=`<div class=\"fs-inspector-line fs-cmd ${e.s}\" "
    "title=\"Click to copy · drag to select\" role=\"button\" tabindex=\"0\">${z(e.v)}</div>`})),"
    "t+='<div class=\"fs-inspector-section\">Status:</div>',"
    "this.headers.forEach(e=>{t+=`<div class=\"fs-inspector-line ${e.s}\">${z(e.v)}</div>`}),"
    "t+='<div class=\"fs-inspector-section\">Evidence:</div>',"
    "this.body.forEach(e=>{t+=`<div class=\"fs-inspector-line ${e.s}\">${z(e.v)}</div>`}),"
    "this._contentEl.innerHTML=t"
)


def engine_source() -> str:
    js = (VENDOR / "flowstory.min.js").read_text(encoding="utf-8")
    for old, new in LABELS.items():
        if old not in js:
            raise SystemExit(f"label {old!r} not found in the engine — check the vendored version")
        js = js.replace(old, new)
    if _INSPECTOR_RENDER_OLD not in js:
        raise SystemExit("inspector render block not found after label rewrite — check the vendored version")
    js = js.replace(_INSPECTOR_RENDER_OLD, _INSPECTOR_RENDER_NEW)
    # FlowStory maps lines with `a.value||a.v`, so "" becomes undefined and z() throws,
    # freezing the inspector mid-demo. Prefer nullish coalescing.
    if "a.value||a.v" not in js:
        raise SystemExit("value||v mapper not found in the engine — check the vendored version")
    js = js.replace("a.value||a.v", "a.value??a.v")
    # The bundle is an ES module ending in `export{a as Name,...};`. Inline it
    # and bind the exported names locally instead.
    match = re.search(r"export\{([^}]*)\};?\s*$", js)
    if not match:
        raise SystemExit("export statement not found in the engine")
    bindings = []
    for part in match.group(1).split(","):
        local, _, exported = part.strip().partition(" as ")
        bindings.append(f"{exported or local}={local}")
    return js[: match.start()] + "const " + ",".join(bindings) + ";"


